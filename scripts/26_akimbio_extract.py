#!/usr/bin/env python3
"""
Third benchmark: AkimBio (the UHeads authors' claim-labelled biographies), GPU extraction.

Datasets `llm-uncertainty-head/train_akimbio_{mistral,gemma2}`: biographies generated by
Mistral-7B-Instruct-v0.2 / Gemma-2-9B-it, claims aligned to reply tokens, label
`verified` (1 = unsupported/false, 0 = supported, NaN = unverifiable -> dropped).
The authors' pre-trained heads were trained on these TRAIN splits, so on the test split
GRASP (trained on the same train split) vs UHead is an identical-data comparison.

Per backbone, one teacher-forced pass per answer (the dataset's own input_ids) gives:
  GRASP features  top-4 variance heads per layer, chosen on `--calib` unlabelled train answers
  probabilities   top-24 per token + the chosen token (MUCH format, for features and CCP)
  UHead logits    the authors' pre-trained claim heads for this backbone (test + eval)
CCP (MUCH implementation, delta=24, sigma=8) on a fixed `--ccp-n`-answer test subset.
Claims keep their (possibly non-contiguous) token sets.

    python scripts/26_akimbio_extract.py --much-root /kaggle/tmp/much \
        --uhead-src /kaggle/tmp/llm-uncertainty-head --out /kaggle/working/results/akimbio
"""

from __future__ import annotations

import os

os.environ.setdefault("PYTORCH_CUDA_ALLOC_CONF", "expandable_segments:True")

import argparse
import gc
import importlib.util
import json
import sys
import time
from pathlib import Path
from types import SimpleNamespace

import numpy as np
import torch

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parents[0] / "src"))
from grasp.features import FeatureConfig  # noqa: E402
from grasp.heads import select_heads_variance_topk  # noqa: E402


def _load(name, file):
    spec = importlib.util.spec_from_file_location(name, HERE / file)
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


rt15 = _load("rt15", "15_ragtruth_extract.py")
u17 = _load("u17", "17_uhead_extract.py")

BACKBONES = {
    "mistral": {"dataset": "llm-uncertainty-head/train_akimbio_mistral",
                "model": "mistralai/Mistral-7B-Instruct-v0.2",
                "heads": ["uhead_claim_exp5_Mistral-7B-Instruct-v0.2", "uhead_claim_exp6_Mistral-7B-Instruct-v0.2"]},
    "gemma2": {"dataset": "llm-uncertainty-head/train_akimbio_gemma2",
               "model": "google/gemma-2-9b-it",
               "heads": ["uhead_claim_exp2_gemma-2-9b-it"]},
}


def split_ids(tok, ex):
    """(prompt_len, output_ids, claims as output-token index lists, labels)."""
    ids = list(ex["input_ids"])
    reply_ids = tok(ex["reply"], add_special_tokens=False)["input_ids"]
    # context = everything before the reply; the reply tokens are the tail of input_ids
    ctx = len(ids) - len(reply_ids)
    if ids[ctx:] != reply_ids:  # fall back: locate the reply by searching for its first tokens
        for c in range(len(ids) - 1, 0, -1):
            if ids[c : c + 8] == reply_ids[:8]:
                ctx = c
                break
    out = ids[ctx:]
    nonspecial = [i for i, t in enumerate(out) if t not in tok.all_special_ids]
    claims, labels = [], []
    for c, v in zip(ex["claims"], ex["verified"]):
        if v is None or v != v:
            continue
        pos = [nonspecial[i] for i in c["aligned_token_ids"] if i < len(nonspecial)]
        if pos:
            claims.append(pos)
            labels.append(int(v == 1.0))
    return ctx, out, claims, labels


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--much-root", type=Path, required=True)
    ap.add_argument("--uhead-src", type=Path, required=True)
    ap.add_argument("--out", type=Path, required=True)
    ap.add_argument("--backbones", default="mistral,gemma2")
    ap.add_argument("--n-train", type=int, default=1000)
    ap.add_argument("--calib", type=int, default=100)
    ap.add_argument("--ccp-n", type=int, default=50)
    ap.add_argument("--limit", type=int, default=0)
    args = ap.parse_args()
    from datasets import load_dataset
    from transformers import AutoTokenizer

    Auto = u17.import_luh(args.uhead_src)
    for bb in args.backbones.split(","):
        spec = BACKBONES[bb]
        out = args.out / bb
        (out / "features").mkdir(parents=True, exist_ok=True)
        ds = load_dataset(spec["dataset"])
        rng = np.random.RandomState(0)
        tr_idx = sorted(rng.choice(len(ds["train"]), min(args.n_train, len(ds["train"])), replace=False))
        groups = {"train": [ds["train"][int(i)] for i in tr_idx], "eval": list(ds["eval"]), "test": list(ds["test"])}
        if args.limit:
            groups = {k: v[: args.limit] for k, v in groups.items()}
        tok = AutoTokenizer.from_pretrained(spec["model"])
        model = u17.load_llm(spec["model"])
        t0 = time.time()

        # label-free head selection on unlabelled train answers
        calib = []
        for ex in groups["train"][: args.calib]:
            ctx, outi, _, _ = split_ids(tok, ex)
            f = rt15.teacher_forced_ids(model, ex["input_ids"], ctx,
                                        FeatureConfig(keep_heads=None, align="current", saliency_norm="per_later_token"))
            calib.append(f)
        heads = select_heads_variance_topk(calib, k=4)
        del calib; gc.collect()
        cfg = FeatureConfig(keep_heads=heads, align="current", saliency_norm="per_later_token")
        (out / "meta_heads.json").write_text(json.dumps({str(k): v for k, v in heads.items()}))

        uheads = {h: Auto.from_pretrained(f"llm-uncertainty-head/{h}", base_model=SimpleNamespace(
            config=getattr(model.config, "text_config", None) or model.config)).to(
            "cuda:0" if torch.cuda.is_available() else "cpu").eval() for h in spec["heads"]}

        meta = []
        for split, rows in groups.items():
            for k, ex in enumerate(rows):
                rid = f"{split}_{k}"
                ctx, outi, claims, labels = split_ids(tok, ex)
                if not claims:
                    continue
                ids = torch.tensor([list(ex["input_ids"])]).to(model.device)
                try:
                    f, ti, tp, ch = rt15.teacher_forced_ids(model, ex["input_ids"], ctx, cfg, with_probs=True)
                    uh = {}
                    if split != "train":
                        for h, head in uheads.items():
                            uh[h] = u17.score_claims(head, model, ids, ctx, claims)
                except torch.OutOfMemoryError:
                    torch.cuda.empty_cache(); print(f"  skip {rid}: OOM", flush=True); continue
                flat = np.concatenate([np.asarray(c, np.int32) for c in claims])
                np.savez_compressed(out / "features" / f"{rid}.npz", feats=f.astype(np.float16), top_i=ti,
                                    top_p=tp.astype(np.float16), chosen=ch, out_ids=np.asarray(outi, np.int32),
                                    chunk_flat=flat, chunk_len=np.asarray([len(c) for c in claims], np.int32))
                meta.append({"id": rid, "split": split, "labels": labels, "uhead": uh, "n_tokens": len(outi)})
            print(f"{bb} {split}: {sum(m['split'] == split for m in meta)} answers ({time.time() - t0:.0f}s)", flush=True)
        (out / "meta.jsonl").write_text("\n".join(json.dumps(m) for m in meta), encoding="utf-8")
        print(f"AKIMBIO-EXTRACT {bb}: {len(meta)} answers, "
              f"{sum(len(m['labels']) for m in meta)} claims", flush=True)
        del model, uheads; gc.collect(); torch.cuda.empty_cache()

        # CCP on a fixed test subset (answers 0..ccp_n-1), same GPU
        sys.path.insert(0, str(args.much_root))
        import src.signals.sig_ccp as sig_ccp_mod  # type: ignore
        from src.signals.sig_ccp import SignalCCP  # type: ignore
        if not torch.cuda.is_available():
            sig_ccp_mod.DEVICE = torch.device("cpu")
        ccp = SignalCCP(delta=24, sigma=8)
        vals, secs = {}, []
        for m in [m for m in meta if m["split"] == "test"][: args.ccp_n]:
            z = np.load(out / "features" / f"{m['id']}.npz")
            oi = z["out_ids"].tolist()
            gen = SimpleNamespace(output_tokens=oi, topn_prob_dicts=rt15.topn_dicts(z["top_i"], z["top_p"], z["chosen"], oi),
                                  generation_cfg=SimpleNamespace(model_name=spec["model"]))
            t1 = time.perf_counter()
            vals[m["id"]] = [float(x) for x in ccp.compute_signal_value(gen)]
            secs.append(time.perf_counter() - t1)
        (out / "ccp_test.json").write_text(json.dumps(vals))
        print(f"AKIMBIO-CCP {bb}: {len(vals)} answers, {np.mean(secs) if secs else 0:.1f}s each", flush=True)
    print("done", flush=True)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
