def ai_declaration():
    d = new_doc()
    heading(d, "Declaration on the use of AI tools")
    d.add_paragraph(
        "During this work the author used Claude (Anthropic), an AI assistant, for the "
        "following tasks:")
    for item in (
            "writing and running the scripts that queried OpenAlex and the arXiv API and "
            "exported the records;",
            "proposing title and abstract screening decisions from keyword rules (each decision "
            "is marked in the Screening_Sheet for confirmation by the author);",
            "helping extract fields from full texts into the workbook and re-checking quality "
            "ratings against the PDFs;",
            "resolving every DOI and comparing registered titles with the cited titles;",
            "writing the scripts that produce the figures and assemble the manuscript;",
            "drafting the manuscript text."):
        d.add_paragraph(item, style="List Bullet")
    d.add_paragraph(
        "The author checked the counts against the workbook, reviewed the text and takes full "
        "responsibility for the content of the manuscript. No AI tool is listed as an author.")
    p = d.add_paragraph()
    r = p.add_run(
        "Note for the author (delete before submission): the course handout requires an "
        "AI-free manuscript and says copying wording from AI tools is not acceptable. Before "
        "submitting, rewrite the manuscript text in your own words, then edit this declaration "
        "so that it describes exactly what you used AI for. Do not submit a declaration that "
        "understates AI use.")
    r.italic = True
    d.save(OUT / "AI_Use_Declaration.docx")


def journal_check():
    d = new_doc()
    heading(d, "Journal shortlist and check")
    d.add_paragraph(
        "Three candidate venues that publish reviews on language-model methods. Nothing in this "
        "table has been verified on the submission date: check every row on the journal's own "
        "site and in the official Scopus source list before choosing, because indexing, fees "
        "and limits change.")
    checks = [
        "Currently listed as Scopus-indexed? (check Scopus source list on submission date)",
        "Publishes review or survey articles? Word and reference limits?",
        "Scope matches the topic? (read titles of its recent reviews)",
        "Figures, tables and reference style fit its template?",
        "Requires similarity report, structured abstract, highlights, data statement or "
        "AI-use declaration?",
        "Article-processing charges or submission fees?",
        "Real peer review and transparent editorial board?",
        "Realistic review time (received / accepted dates of recent papers)?",
    ]
    cands = ["Artificial Intelligence Review (Springer)", "IEEE Access (IEEE)",
             "Discover Artificial Intelligence (Springer)"]
    table(d, ["Check"] + cands, [[c, "", "", ""] for c in checks], [6.0, 3.5, 3.5, 3.5])
    d.add_paragraph()
    d.add_paragraph(
        "Starting points to verify: Artificial Intelligence Review publishes surveys and has a "
        "subscription route without an APC; IEEE Access and Discover Artificial Intelligence "
        "are open access with an APC. Ask your supervisor which venues the course accepts. "
        "Once you choose, reformat the manuscript to that journal's template and word limit.")
    d.save(OUT / "Journal_Shortlist_Check.docx")


