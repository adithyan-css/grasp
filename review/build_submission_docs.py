def new_doc():
    d = Document()
    st = d.styles["Normal"]
    st.font.name = "Times New Roman"
    st.font.size = Pt(11)
    st.element.rPr.rFonts.set(qn("w:eastAsia"), "Times New Roman")
    for s in d.sections:
        s.page_width, s.page_height = Cm(21.59), Cm(27.94)
        for side in ("left_margin", "right_margin", "top_margin", "bottom_margin"):
            setattr(s, side, Cm(2.54))
    return d


def heading(d, text):
    p = d.add_paragraph()
    r = p.add_run(text)
    r.bold = True
    r.font.size = Pt(13)


def table(d, header, rows, widths):
    t = d.add_table(rows=1, cols=len(header))
    t.style = "Table Grid"
    t.alignment = WD_TABLE_ALIGNMENT.CENTER
    for cells, vals, bold in [(t.rows[0].cells, header, True)] + [(None, r, False) for r in rows]:
        cells = cells or t.add_row().cells
        for c, v, w in zip(cells, vals, widths):
            c.width = Cm(w)
            run = c.paragraphs[0].add_run(str(v))
            run.font.size = Pt(9.5)
            run.bold = bold
            if bold:
                shd = OxmlElement("w:shd")
                shd.set(qn("w:val"), "clear")
                shd.set(qn("w:fill"), "D9E2F3")
                c._tc.get_or_add_tcPr().append(shd)
    return t


def cover_letter():
    d = new_doc()
    for line in (AUTHOR, AFFIL, EMAIL, "[DATE]", "", "The Editor", JOURNAL, ""):
        d.add_paragraph(line).paragraph_format.space_after = Pt(0)
    d.add_paragraph("Dear Editor,")
    d.add_paragraph(
        f'I submit the manuscript "{TITLE}" for consideration as a review article in {JOURNAL}.')
    d.add_paragraph(
        "The review addresses how hallucinations in text generated by large language models "
        "are detected automatically, at the level of whole responses, sentences, token spans "
        "and individual claims. It covers 54 primary studies from 2022 to 2026, selected "
        "through a documented OpenAlex and arXiv search whose strings, counts and exports are "
        "supplied as supplementary material.")
    d.add_paragraph(
        "Existing reviews of hallucination (Huang et al., ACM TOIS 2025), uncertainty "
        "quantification (Shorinwa et al., ACM Computing Surveys 2025; Geng et al., NAACL 2024; "
        "Kang et al., 2025) and abstention (Wen et al., TACL 2025) cover detection methods, but "
        "none of them states its search strategy, codes the granularity or compute cost of "
        "each detector, or counts how often studies report variance, transfer tests, cost or "
        "non-English evaluation.")
    d.add_paragraph(
        "The contributions are a four-axis taxonomy of 46 detectors with an assignment rule for "
        "each category; a comparison table of all 54 studies that does not rank results across "
        "different settings; counts of evaluation and reproducibility practice (for example, "
        "15 of 54 studies report variance or significance tests and 10 of 54 measure compute "
        "cost); and nine research gaps, each backed by counts and paired with a proposed study.")
    d.add_paragraph(
        "The manuscript is original, has not been published or submitted elsewhere, and the "
        "author approves it. Author contributions and declarations are stated in the "
        "manuscript. Corresponding author: " + f"{AUTHOR}, {EMAIL}.")
    d.add_paragraph("Sincerely,")
    d.add_paragraph(AUTHOR)
    d.save(OUT / "Cover_Letter.docx")


