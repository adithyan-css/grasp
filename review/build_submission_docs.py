def package():
    for name in ("Review_Manuscript_Hallucination_Detection.docx",
                 "Review_Manuscript_Hallucination_Detection.pdf"):
        shutil.copy2(HERE / name, OUT / name)
    figs = OUT / "Figures"
    figs.mkdir(exist_ok=True)
    for f in sorted((HERE / "figures").glob("fig*.png")):
        shutil.copy2(f, figs / f.name)
    shutil.copy2(HERE / "Review_Workbook_GRASP.xlsx", OUT / "Supplementary_S1_Review_Workbook.xlsx")
    with zipfile.ZipFile(OUT / "Supplementary_S2_Search_Exports.zip", "w",
                         zipfile.ZIP_DEFLATED) as z:
        for f in sorted((HERE / "search_exports").iterdir()):
            z.write(f, f.name)


